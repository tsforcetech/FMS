export function ui(l: Lang) {
  const d = dicts[l];
  const s = (k: string) => d[k] ?? en[k] ?? k;
  const proxy = new Proxy({} as Record<string, string>, { get: (_, k: string) => s(k) });
  return Object.assign(proxy, {
    module: (m: string) => modulesT[l][m] || m,
    category: (_id: string, label: string) => d['cat.' + _id] || label,
    role: (r: string) => s('role.' + r),
    app: (a: string) => s('app.' + a),
    articlesCount: (n: number) => `${n} ${s('articles')}`,
  }) as unknown as Record<string, string> & {
    module: (m: string) => string;
    category: (id: string, label: string) => string;
    role: (r: string) => string;
    app: (a: string) => string;
    articlesCount: (n: number) => string;
  };
}
