/**
 * Phase 8 Excel and PDF writers. Libraries are imported lazily so the apps
 * only download them when someone exports. Both writers take a PreparedTable
 * (already sanitised and filtered by exporting.ts) and never add numbers of
 * their own: totals come from the prepared rows.
 */
import {
  formatCell,
  needsUnicodeFont,
  safeText,
  type ExportMeta,
  type PreparedTable,
} from './exporting';

export type Branding = {
  /** data:image/png|jpeg;base64,… (small, stored in company settings). */
  logoDataUrl?: string;
  /** #RRGGBB used for table headers. */
  primaryColor?: string;
};
/** Supplies a Unicode TTF (base64) when the content needs one. */
export type FontLoader = () => Promise<{ regular: string; bold?: string }>;

const numFmt: Record<string, string> = {
  number: '#,##0.##',
  minutes: '#,##0',
  money: '#,##0.00',
  percent: '0.0"%"',
  date: 'dd mmm yyyy',
  datetime: 'dd mmm yyyy hh:mm',
};
const argb = (hex = '#1D4ED8') =>
  'FF' + hex.replace('#', '').toUpperCase().padStart(6, '0').slice(0, 6);

/** Shifts a Date so Excel (which has no time zones) shows company local time. */
function localDate(d: Date, timeZone: string) {
  const p = Object.fromEntries(
    new Intl.DateTimeFormat('en-GB', {
      timeZone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hourCycle: 'h23',
    })
      .formatToParts(d)
      .map((x) => [x.type, x.value]),
  );
  return new Date(
    Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour, +p.minute, +p.second),
  );
}

export async function buildXlsx(
  meta: ExportMeta,
  t: PreparedTable,
  branding: Branding = {},
): Promise<Uint8Array> {
  const ExcelJS = (await import('exceljs')).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = 'FacilityOS';
  wb.created = meta.generatedAt;
  const ws = wb.addWorksheet(
    safeText(meta.title)
      .slice(0, 31)
      .replace(/[\\/?*[\]:']/g, ' ') || 'Report',
    {
      views: [{ state: 'frozen', ySplit: 1 }],
    },
  );
  ws.columns = t.columns.map((c) => ({
    header: safeText(c.label),
    key: c.key,
    width:
      c.width ||
      Math.min(
        60,
        Math.max(
          10,
          c.label.length + 2,
          ...t.rows.slice(0, 200).map((r, ri) => {
            const v = r[t.columns.indexOf(c)];
            void ri;
            return typeof v === 'string' ? Math.min(v.length, 60) : 12;
          }),
        ),
      ),
    style: numFmt[c.type]
      ? { numFmt: numFmt[c.type] }
      : { alignment: { wrapText: true, vertical: 'top' } },
  }));
  const head = ws.getRow(1);
  head.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  head.fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: argb(branding.primaryColor) },
  };
  head.alignment = { vertical: 'middle', wrapText: true };
  for (const r of t.rows)
    ws.addRow(
      r.map((v) => (v instanceof Date ? localDate(v, meta.timeZone) : v)),
    );
  if (t.totals) {
    const row = ws.addRow(
      t.totals.map((v, i) => (v === null ? (i === 0 ? 'Total' : null) : v)),
    );
    row.font = { bold: true };
    row.border = { top: { style: 'thin' } };
  }
  ws.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: Math.max(1, t.columns.length) },
  };
  // Report details on a second sheet keep the data sheet a clean table.
  const info = wb.addWorksheet('Report details');
  info.columns = [
    { header: 'Item', key: 'k', width: 24 },
    { header: 'Value', key: 'v', width: 80 },
  ];
  info.getRow(1).font = { bold: true };
  for (const [k, v] of [
    ['Report', meta.title],
    ['Company', meta.companyName],
    ['Period', meta.period || '—'],
    ...meta.filters.map((f) => [f.label, f.value]),
    ['Rows', String(t.rows.length)],
    ['Generated', `${meta.generatedAt.toISOString()} (${meta.timeZone})`],
    ...(meta.generatedBy ? [['Generated by', meta.generatedBy]] : []),
  ])
    info.addRow({ k: safeText(k), v: safeText(v) });
  const buf = await wb.xlsx.writeBuffer();
  return new Uint8Array(buf as ArrayBuffer);
}

export async function buildPdf(
  meta: ExportMeta,
  t: PreparedTable,
  branding: Branding = {},
  loadFont?: FontLoader,
): Promise<Uint8Array> {
  const { jsPDF } = await import('jspdf');
  const autoTable = (await import('jspdf-autotable')).default;
  const landscape = t.columns.length > 6;
  const doc = new jsPDF({
    orientation: landscape ? 'landscape' : 'portrait',
    unit: 'pt',
    format: 'a4',
  });
  let font = 'helvetica';
  if (needsUnicodeFont(t, meta) && loadFont) {
    const f = await loadFont();
    doc.addFileToVFS('Unicode.ttf', f.regular);
    doc.addFont('Unicode.ttf', 'Unicode', 'normal');
    if (f.bold) {
      doc.addFileToVFS('Unicode-Bold.ttf', f.bold);
      doc.addFont('Unicode-Bold.ttf', 'Unicode', 'bold');
    }
    font = 'Unicode';
  }
  const W = doc.internal.pageSize.getWidth();
  const M = 36;
  let y = M;
  if (
    branding.logoDataUrl &&
    /^data:image\/(png|jpeg);base64,/.test(branding.logoDataUrl)
  ) {
    try {
      const type = branding.logoDataUrl.includes('png') ? 'PNG' : 'JPEG';
      doc.addImage(branding.logoDataUrl, type, M, y, 0, 36);
    } catch {
      /* an unreadable logo never blocks the report */
    }
  }
  doc.setFont(font, 'bold');
  doc.setFontSize(15);
  doc.text(meta.title, W - M, y + 12, { align: 'right' });
  doc.setFont(font, 'normal');
  doc.setFontSize(9);
  doc.text(meta.companyName, W - M, y + 26, { align: 'right' });
  y += 48;
  const lines = [
    ...(meta.header ? [meta.header] : []),
    ...(meta.period ? [`Period: ${meta.period}`] : []),
    ...meta.filters.map((f) => `${f.label}: ${f.value}`),
    `Generated: ${meta.generatedAt.toLocaleString('en-GB', { timeZone: meta.timeZone })} (${meta.timeZone})${meta.generatedBy ? ' by ' + meta.generatedBy : ''} · ${t.rows.length} rows`,
  ];
  doc.setFontSize(8.5);
  for (const l of lines) {
    const wrapped = doc.splitTextToSize(l, W - 2 * M) as string[];
    doc.text(wrapped, M, y);
    y += 11 * wrapped.length;
  }
  const head = [t.columns.map((c) => c.label)];
  const body = t.rows.map((r) =>
    r.map((c, i) => String(formatCell(c, t.columns[i].type, meta.timeZone))),
  );
  const foot = t.totals
    ? [
        t.totals.map((v, i) =>
          v === null
            ? i === 0
              ? 'Total'
              : ''
            : String(formatCell(v, t.columns[i].type, meta.timeZone)),
        ),
      ]
    : undefined;
  const rgb = (branding.primaryColor || '#1D4ED8').replace('#', '');
  const color: [number, number, number] = [0, 2, 4].map(
    (i) => parseInt(rgb.slice(i, i + 2), 16) || 0,
  ) as [number, number, number];
  autoTable(doc, {
    startY: y + 4,
    head,
    body,
    foot,
    showFoot: 'lastPage',
    margin: { left: M, right: M, bottom: 40 },
    styles: {
      font,
      fontSize: t.columns.length > 9 ? 7 : 8,
      cellPadding: 3,
      overflow: 'linebreak',
      valign: 'top',
    },
    headStyles: { fillColor: color, textColor: 255, fontStyle: 'bold' },
    footStyles: {
      fillColor: [241, 245, 249],
      textColor: 20,
      fontStyle: 'bold',
    },
    columnStyles: Object.fromEntries(
      t.columns.map((c, i) => [
        i,
        ['number', 'minutes', 'money', 'percent'].includes(c.type)
          ? { halign: 'right' }
          : {},
      ]),
    ),
    didDrawPage: () => {
      const H = doc.internal.pageSize.getHeight();
      doc.setFont(font, 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(110);
      doc.text(meta.footer || `${meta.companyName} · ${meta.title}`, M, H - 20);
      doc.setTextColor(0);
    },
  });
  // Page numbers after the table so the total page count is known.
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    const H = doc.internal.pageSize.getHeight();
    doc.setFont(font, 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(110);
    doc.text(`Page ${i} of ${pages}`, W - M, H - 20, { align: 'right' });
  }
  if (!t.rows.length) {
    doc.setPage(1);
    doc.setFontSize(10);
    doc.text('No records match the selected filters.', M, y + 40);
  }
  return new Uint8Array(doc.output('arraybuffer'));
}
